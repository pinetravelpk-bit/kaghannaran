/**
 * Generates supabase/seed.sql from the data in lib/seed (stops, places, trails,
 * business types & approval rules, road segments). Sample listings are NOT included.
 *   npm run seed:sql
 */
import { writeFileSync } from "node:fs";
import { STOPS } from "../lib/seed/stops";
import { BUSINESS_TYPES } from "../lib/seed/business-types";
import { TRAILS, ROAD_SEGMENTS, DEFAULT_SETTINGS } from "../lib/seed/index";

const q = (v: unknown) => (v === undefined || v === null || v === "" ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;

let sql = "-- Generated by scripts/generate-seed.ts: reference data for Kaghan Naran Directory\nbegin;\n\n";
for (const s of STOPS) {
  sql += `insert into public.stops (slug, sort_order, name, name_ur, kind, side_trip, altitude, description, image_url, places) values (${q(s.slug)}, ${s.order}, ${q(s.name)}, ${q(s.nameUr)}, ${q(s.kind)}, ${!!s.sideTrip}, ${q(s.altitude)}, ${q(s.desc)}, ${q(s.image)}, ${j(s.places)})\n  on conflict (slug) do update set sort_order = excluded.sort_order, name = excluded.name, name_ur = excluded.name_ur, kind = excluded.kind, side_trip = excluded.side_trip, altitude = excluded.altitude, description = excluded.description, image_url = excluded.image_url, places = excluded.places;\n`;
}
sql += "\n";
for (const t of BUSINESS_TYPES) {
  sql += `insert into public.business_types (slug, name, grp, icon, description, individual, admin_only, fields, documents, checklist) values (${q(t.slug)}, ${q(t.name)}, ${q(t.group)}, ${q(t.icon)}, ${q(t.description)}, ${!!t.individual}, ${!!t.adminOnly}, ${j(t.fields)}, ${j(t.documents)}, ${j(t.checklist)})\n  on conflict (slug) do update set name = excluded.name, grp = excluded.grp, icon = excluded.icon, description = excluded.description, individual = excluded.individual, admin_only = excluded.admin_only, fields = excluded.fields, documents = excluded.documents, checklist = excluded.checklist;\n`;
}
sql += "\n";
TRAILS.forEach((t, i) => {
  sql += `insert into public.trails (slug, name, mode, start_from, time_note, stop_slug, sort_order) values (${q(t.slug)}, ${q(t.name)}, ${q(t.mode)}, ${q(t.from)}, ${q(t.time)}, ${q(t.stop)}, ${i}) on conflict (slug) do nothing;\n`;
});
sql += "\n-- road segments (only if the table is empty)\n";
sql += `insert into public.road_segments (segment, note, status, sort_order)\nselect * from (values\n${ROAD_SEGMENTS.map((r, i) => `  (${q(r.segment)}, ${q(r.note)}, ${q(r.status)}::road_status, ${i})`).join(",\n")}\n) v where not exists (select 1 from public.road_segments);\n\n`;
sql += `update public.site_settings set alert_banner = ${q(DEFAULT_SETTINGS.alertBanner)} where id = 1 and alert_banner = '';\n\ncommit;\n\n`;
sql += "-- After you sign up, make yourself admin:\n-- update public.profiles set role = 'admin' where email = 'you@example.com';\n";
writeFileSync("supabase/seed.sql", sql);
console.log(`Wrote supabase/seed.sql (${STOPS.length} stops, ${BUSINESS_TYPES.length} types, ${TRAILS.length} trails)`);
